const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const ENV_PATH = path.join(ROOT_DIR, '.env');
const OUT_ENV_FILE = path.join(ROOT_DIR, 'background', 'env-config.js');
const DIST_DIR = path.join(ROOT_DIR, 'dist');

function parseDotEnv(content) {
  const result = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eqIdx = line.indexOf('=');
    if (eqIdx === -1) continue;
    const key = line.slice(0, eqIdx).trim();
    let value = line.slice(eqIdx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (key) {
      result[key] = value;
    }
  }
  return result;
}

function loadEnv() {
  const fileEnv = fs.existsSync(ENV_PATH)
    ? parseDotEnv(fs.readFileSync(ENV_PATH, 'utf8'))
    : {};

  return {
    CMD_API_KEY: process.env.CMD_API_KEY ?? fileEnv.CMD_API_KEY ?? '',
    CMD_BASE_URL:
      process.env.CMD_BASE_URL ??
      fileEnv.CMD_BASE_URL ??
      'https://api.commandcode.ai/provider/v1',
    CMD_MODEL: process.env.CMD_MODEL ?? fileEnv.CMD_MODEL ?? 'typesafe/jev',
    CF_AIG_AUTH: process.env.CF_AIG_AUTH ?? fileEnv.CF_AIG_AUTH ?? ''
  };
}

function writeEnvConfig(env) {
  const banner = '// Auto-generated by scripts/build.js from .env (gitignored). Do not commit.\n';
  const body = `globalThis.__YT_AI_FILTER_ENV__ = ${JSON.stringify(env, null, 2)};\n`;
  fs.writeFileSync(OUT_ENV_FILE, banner + body, 'utf8');
}

function copyRecursive(src, dest) {
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    fs.mkdirSync(dest, { recursive: true });
    for (const entry of fs.readdirSync(src)) {
      copyRecursive(path.join(src, entry), path.join(dest, entry));
    }
  } else {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(src, dest);
  }
}

function buildDist() {
  fs.rmSync(DIST_DIR, { recursive: true, force: true });
  fs.mkdirSync(DIST_DIR, { recursive: true });

  const entriesToCopy = ['manifest.json', 'icons', 'background', 'content', 'popup'];
  for (const entry of entriesToCopy) {
    const srcPath = path.join(ROOT_DIR, entry);
    if (fs.existsSync(srcPath)) {
      copyRecursive(srcPath, path.join(DIST_DIR, entry));
    }
  }
}

const env = loadEnv();
writeEnvConfig(env);
buildDist();

const keyStatus = env.CMD_API_KEY ? 'present (loaded from env)' : 'empty (configure in popup UI)';
console.log(`Built extension -> dist/ (CMD_API_KEY: ${keyStatus})`);
